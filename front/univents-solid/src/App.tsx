import { RouterProvider, createRouter } from "@tanstack/solid-router";
import {
  configureApiClient,
  createAppFetchers,
  createOrvalTransport,
} from "@trieoh/api-client";
import {
  TanStackQueryProvider,
  createQueryClient,
} from "@trieoh/front-core/solid";
import type { RouterSession } from "@trieoh/front-core/solid";
import { AuthProvider, useAuth } from "@trieoh/identityx-sdk-ts-solid";
import { untrack } from "solid-js";
import { ThemeProvider } from "@/shared/lib/theme";
import "./App.css";

const { authFetcher, publicFetcher } = createAppFetchers({
  apiURL: import.meta.env.VITE_API_URL ?? "http://localhost:8081",
  authAPIURL: import.meta.env.VITE_AUTH_API_URL,
});
configureApiClient({
  baseURL: import.meta.env.VITE_API_URL ?? "http://localhost:8081",
  transport: createOrvalTransport(authFetcher),
  publicTransport: createOrvalTransport(publicFetcher),
});

// Generated by @tanstack/router-plugin from the files under src/routes —
// TanStack derives full typesafety for <Link>, params, and loader data
// from this tree.
import { routeTree } from "./routeTree.gen";
import WaveSpinnerLoading from "./shared/ui/loader/WaveSpinnerLoading";

const router = createRouter({
  routeTree,
  defaultPreload: 'intent',
  context: {
    session: undefined as RouterSession | undefined,
  },
  defaultPendingComponent: () => <main>Loading…</main>,
});

// Registers the router's types library-wide, so `to`/`params` on every
// <Link> typecheck against the actual routes.
declare module "@tanstack/solid-router" {
  interface Register {
    router: typeof router;
  }
}

// The app root: the plugin's generated entries render this component,
// wrapped in src/Document.tsx.
export default function App() {
  return (
    <TanStackQueryProvider client={createQueryClient()}>
      <ThemeProvider>
        <AuthProvider
          baseURL={import.meta.env.VITE_AUTH_API_URL}
          projectId={import.meta.env.VITE_TRIEOH_AUTH_PROJECT_ID}
          fallback={
            <div class="h-screen w-screen flex items-center justify-center">
              <WaveSpinnerLoading text="Carregando..." />
            </div>
          }
        >
          <RouterHost />
        </AuthProvider>
      </ThemeProvider>
    </TanStackQueryProvider>
  );
}

// <AuthProvider> only renders its children once the session has settled, so by
// the time this mounts `isAuthenticated` is final. Seeding it into the router
// context here makes it visible to the very first `beforeLoad`; otherwise the
// guards run against `session: undefined` and bounce authenticated users to
// /auth for a frame before <AuthContextUpdater> catches up.
function RouterHost() {
  const auth = useAuth();

  return (
    <RouterProvider
      router={router}
      context={{
        session: {
          service: auth.auth,
          isAuthenticated: untrack(auth.isAuthenticated),
        },
      }}
    />
  );
}
