// prelude is the package's fixed part: the shared cases every Backend maps
// the same way, run after the Backend's own switch.
const prelude = `// Code generated by tools/problemgen. DO NOT EDIT.

// Package problems holds the Backend's declared problems (RFC 9457): one
// constructor per problem in its problems.yml and the shared
// api/problems.yml, the docs served at /problems/{slug}, and Mapper.
// A constructor's Type is the bare slug; the writer resolves it against the
// Backend's API_URL.
package problems

import (
	"encoding/json"
	"errors"

	"lib/authz"
	"lib/database"
	"lib/httpserver"
	"lib/validator"

	idx "sdk/identityx"

	fp "github.com/MintzyG/problematic"
)

// BatchItem is one failed item of a batch, answered as its own problem.
type BatchItem struct {
	ID      string      ` + "`json:\"id\"`" + `
	Problem *fp.Problem ` + "`json:\"problem\"`" + `
}

// Mapper answers err with app, the Backend's own switch, then with the
// shared cases. An error neither knows is the generic 500.
func Mapper(app fp.ErrorMapper) fp.ErrorMapper {
	var m fp.ErrorMapper
	m = func(err error) *fp.Problem {
		if p := app(err); p != nil {
			return p
		}
		if p := shared(err, m); p != nil {
			return p
		}
		return InternalServerError("Internal Server Error")
	}
	return m
}

// shared maps the lib errors every Backend answers alike. A batch's items
// go through the whole mapper m.
func shared(err error, m fp.ErrorMapper) *fp.Problem {
	var (
		notFound *database.NotFoundError
		batch    *database.BatchError
		invalid  *validator.Error
	)
	switch {
	case errors.As(err, &notFound):
		return NotFound(notFound.Error())
	case errors.Is(err, database.ErrNotFound):
		return NotFound(database.ErrNotFound.Error())
	case errors.As(err, &batch):
		items := make([]BatchItem, len(batch.Items))
		for i, item := range batch.Items {
			items[i] = BatchItem{ID: item.ID, Problem: fp.FromError(item.Err, m)}
		}
		return BatchFailed(batch.Error(), items)
	case errors.As(err, &invalid):
		return Validation(invalid.Error())
	case errors.Is(err, authz.ErrInsufficientRole):
		return InsufficientRole(authz.ErrInsufficientRole.Error())
	case errors.Is(err, idx.ErrNoIdentity):
		return Unauthenticated(idx.ErrNoIdentity.Error())
	}
	return nil
}
`

func (b *bundler) goSource() ([]byte, error) {
	var s strings.Builder
	s.WriteString(prelude)
	for _, p := range b.problems {
		writeConstructor(&s, p)
	}

	s.WriteString("\n// Docs documents every declared problem, for GET /problems/{slug}.\n")
	s.WriteString("var Docs = []httpserver.ProblemDoc{\n")
	for _, p := range b.problems {
		fmt.Fprintf(&s, "\t{Slug: %q, Status: %d, Title: %q, Description: %q, Extensions: json.RawMessage(%s)},\n",
			p.Slug, p.Status, p.Title, p.Description, goString(p.extensionsExample()))
	}
	s.WriteString("}\n")

	src, err := format.Source([]byte(s.String()))
	if err != nil {
		return nil, fmt.Errorf("generated Go does not parse: %w\n%s", err, s.String())
	}
	return src, nil
}

func writeConstructor(s *strings.Builder, p *problem) {
	params := make([]string, 0, 1+len(p.Members))
	params = append(params, "detail string")
	for _, m := range p.Members {
		params = append(params, m.Param+" "+m.GoType)
	}
	fmt.Fprintf(s, "\n// %s is %s (%d %s): %s\n", p.Name, p.Slug, p.Status, p.Title, oneLine(p.Description))
	fmt.Fprintf(s, "func %s(%s) *fp.Problem {\n", p.Name, strings.Join(params, ", "))
	fmt.Fprintf(s, "\treturn fp.New(%d).WithType(%q).WithTitle(%q).WithDetail(detail)", p.Status, p.Slug, p.Title)
	for _, m := range p.Members {
		fmt.Fprintf(s, ".\n\t\tWithExtension(%q, %s)", m.Name, m.Param)
	}
	s.WriteString("\n}\n")
}

// extensionsExample is p's extension members as an example JSON object.
func (p *problem) extensionsExample() []byte {
	var s strings.Builder
	s.WriteByte('{')
	for i, m := range p.Members {
		if i > 0 {
			s.WriteByte(',')
		}
		s.WriteString(strconv.Quote(m.Name))
		s.WriteByte(':')
		s.Write(m.Example)
	}
	s.WriteByte('}')
	return []byte(s.String())
}

// param is a member's JSON name as a Go parameter: lowerCamel, and never
// a keyword or predeclared identifier.
func param(name string) string {
	var s strings.Builder
	upper := false
	for i, r := range name {
		switch {
		case r == '_' || r == '-' || r == '.':
			upper = true
		case upper && s.Len() > 0:
			s.WriteRune(unicode.ToUpper(r))
			upper = false
		case i == 0:
			s.WriteRune(unicode.ToLower(r))
		default:
			s.WriteRune(r)
		}
	}
	p := s.String()
	if token.IsKeyword(p) || predeclared[p] {
		p += "Value"
	}
	return p
}

var predeclared = map[string]bool{
	"any": true, "bool": true, "byte": true, "error": true, "false": true,
	"float64": true, "int": true, "len": true, "nil": true, "string": true,
	"true": true, "fp": true, "json": true, "errors": true,
}

// goString quotes b as a raw string when it can, so JSON reads as JSON.
func goString(b []byte) string {
	if bytes.ContainsAny(b, "`\r") {
		return strconv.Quote(string(b))
	}
	return "`" + string(b) + "`"
}

func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}
