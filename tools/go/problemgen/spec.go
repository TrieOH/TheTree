const header = "Code generated by tools/problemgen. DO NOT EDIT."

// problemSuffix names a problem's expanded schema and response, so they
// never collide with the authored name or the spec's own components.
const problemSuffix = "Problem"

var (
	slugPattern = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)
	namePattern = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)
	// reserved are the members every problem has; an extension can't be one.
	reserved = []string{"type", "status", "title", "detail", "instance", "errors"}
	methods  = []string{"get", "put", "post", "delete", "options", "head", "patch", "trace"}
	// problemFiles are read relative to the spec: the shared problems, then
	// the Backend's own.
	problemFiles = []string{"../problems.yml", "problems.yml"}
)

// problem is one declared problem.
type problem struct {
	Name        string // authored schema name, and the constructor's
	Slug        string
	Status      int
	Title       string
	Description string
	Members     []member

	xProblem *yaml.Node // the authored x-problem block, kept in the bundle
	file     string
}

// member is one of a problem's extension members.
type member struct {
	Name    string // JSON name
	Param   string // the constructor's parameter
	GoType  string
	Example json.RawMessage

	schema *yaml.Node
}

// namedNode is a plain schema from a problem file, merged into the spec as is.
type namedNode struct {
	name string
	node *yaml.Node
	file string
}

type bundler struct {
	doc      *yaml.Node // the spec's document node
	root     *yaml.Node // its top-level mapping
	schemas  []namedNode
	problems []*problem
}

func load(specPath string) (*bundler, error) {
	doc, err := readYAML(specPath)
	if err != nil {
		return nil, err
	}
	b := &bundler{doc: doc, root: doc.Content[0]}
	dir := filepath.Dir(specPath)
	for _, f := range problemFiles {
		err = b.loadFile(filepath.Join(dir, f))
		if err != nil {
			return nil, err
		}
	}
	err = b.resolveMembers()
	if err != nil {
		return nil, err
	}
	return b, nil
}

func readYAML(path string) (*yaml.Node, error) {
	raw, err := os.ReadFile(path) //nolint:gosec // the Backend's own spec files
	if err != nil {
		return nil, err
	}
	var doc yaml.Node
	err = yaml.Unmarshal(raw, &doc)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return nil, fmt.Errorf("%s: not a YAML mapping", path)
	}
	return &doc, nil
}

func (b *bundler) loadFile(path string) error {
	doc, err := readYAML(path)
	if err != nil {
		return err
	}
	schemas := get(get(doc.Content[0], "components"), "schemas")
	if schemas == nil {
		return nil
	}
	for i := 0; i < len(schemas.Content); i += 2 {
		name, node := schemas.Content[i].Value, schemas.Content[i+1]
		if b.declared(name) {
			return fmt.Errorf("%s: schema %s is declared twice", path, name)
		}
		x := get(node, "x-problem")
		if x == nil {
			b.schemas = append(b.schemas, namedNode{name: name, node: node, file: path})
			continue
		}
		p, err := parseProblem(name, node, x)
		if err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		p.file = path
		for _, q := range b.problems {
			if q.Slug == p.Slug {
				return fmt.Errorf("%s: slug %s is declared by both %s and %s", path, p.Slug, q.Name, p.Name)
			}
		}
		b.problems = append(b.problems, p)
	}
	return nil
}

func (b *bundler) declared(name string) bool {
	for _, s := range b.schemas {
		if s.name == name {
			return true
		}
	}
	for _, p := range b.problems {
		if p.Name == name {
			return true
		}
	}
	return false
}

func parseProblem(name string, node, x *yaml.Node) (*problem, error) {
	var meta struct {
		Slug        string `yaml:"slug"`
		Status      int    `yaml:"status"`
		Title       string `yaml:"title"`
		Description string `yaml:"description"`
	}
	err := x.Decode(&meta)
	if err != nil {
		return nil, fmt.Errorf("%s: x-problem: %w", name, err)
	}
	switch {
	case !namePattern.MatchString(name):
		return nil, fmt.Errorf("%s: a problem's name must be an exported Go identifier", name)
	case !slugPattern.MatchString(meta.Slug):
		return nil, fmt.Errorf("%s: slug %q must be lowercase words joined by hyphens", name, meta.Slug)
	case meta.Status < 400 || meta.Status > 599:
		return nil, fmt.Errorf("%s: status %d is not a 4xx or 5xx", name, meta.Status)
	case meta.Title == "":
		return nil, fmt.Errorf("%s: x-problem needs a title", name)
	case meta.Description == "":
		return nil, fmt.Errorf("%s: x-problem needs a description", name)
	}
	p := &problem{
		Name:        name,
		Slug:        meta.Slug,
		Status:      meta.Status,
		Title:       meta.Title,
		Description: strings.TrimSpace(meta.Description),
		xProblem:    x,
	}
	for k := 0; k < len(node.Content); k += 2 {
		switch key := node.Content[k].Value; key {
		case "x-problem", "type", "required", "properties", "description":
		default:
			return nil, fmt.Errorf("%s: a problem declares only x-problem and its members, not %s", name, key)
		}
	}
	if t := get(node, "type"); t != nil && t.Value != "object" {
		return nil, fmt.Errorf("%s: a problem's type is object", name)
	}
	p.Members, err = parseMembers(node)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", name, err)
	}
	return p, nil
}

// parseMembers reads a problem's extension members, in declared order.
func parseMembers(node *yaml.Node) ([]member, error) {
	var required []string
	if r := get(node, "required"); r != nil {
		err := r.Decode(&required)
		if err != nil {
			return nil, fmt.Errorf("required: %w", err)
		}
	}
	var members []member
	params := map[string]bool{"detail": true}
	if props := get(node, "properties"); props != nil {
		for k := 0; k < len(props.Content); k += 2 {
			m := member{Name: props.Content[k].Value, schema: props.Content[k+1]}
			if slices.Contains(reserved, m.Name) {
				return nil, fmt.Errorf("%s is a standard member, not an extension", m.Name)
			}
			// Every member is always written, so every one is required.
			if !slices.Contains(required, m.Name) {
				return nil, fmt.Errorf("member %s must be required", m.Name)
			}
			m.Param = param(m.Name)
			if params[m.Param] {
				return nil, fmt.Errorf("members collide as parameter %s", m.Param)
			}
			params[m.Param] = true
			members = append(members, m)
		}
	}
	if len(required) != len(members) {
		return nil, errors.New("required lists members it doesn't declare")
	}
	return members, nil
}

// resolveMembers gives every member its Go type and its example value.
func (b *bundler) resolveMembers() error {
	goTypes := map[string]string{}
	for _, s := range b.schemas {
		if t := get(s.node, "x-problem-go-type"); t != nil {
			goTypes[s.name] = t.Value
		}
	}
	for _, p := range b.problems {
		for i := range p.Members {
			m := &p.Members[i]
			t, err := goType(m.schema, goTypes)
			if err != nil {
				return fmt.Errorf("%s: %s.%s: %w", p.file, p.Name, m.Name, err)
			}
			m.GoType = t
			m.Example, err = example(m.schema, t)
			if err != nil {
				return fmt.Errorf("%s: %s.%s: example: %w", p.file, p.Name, m.Name, err)
			}
		}
	}
	return nil
}

func goType(s *yaml.Node, goTypes map[string]string) (string, error) {
	if ref := get(s, "$ref"); ref != nil {
		name, ok := strings.CutPrefix(ref.Value, "#/components/schemas/")
		if !ok {
			return "", fmt.Errorf("$ref %s is not a components schema", ref.Value)
		}
		t, ok := goTypes[name]
		if !ok {
			return "", fmt.Errorf("schema %s has no x-problem-go-type", name)
		}
		return t, nil
	}
	t := get(s, "type")
	if t == nil {
		return "", errors.New("member has no type")
	}
	switch t.Value {
	case "string":
		return "string", nil
	case "integer":
		return "int", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "array":
		items := get(s, "items")
		if items == nil {
			return "", errors.New("array has no items")
		}
		elem, err := goType(items, goTypes)
		if err != nil {
			return "", err
		}
		return "[]" + elem, nil
	}
	return "", fmt.Errorf("type %s has no Go type; $ref a schema with x-problem-go-type", t.Value)
}

// example is the member's documented example: its own, else its type's zero.
func example(s *yaml.Node, goType string) (json.RawMessage, error) {
	if e := get(s, "example"); e != nil {
		var v any
		err := e.Decode(&v)
		if err != nil {
			return nil, err
		}
		return json.Marshal(v)
	}
	switch {
	case goType == "string":
		return json.RawMessage(`""`), nil
	case goType == "int", goType == "float64":
		return json.RawMessage(`0`), nil
	case goType == "bool":
		return json.RawMessage(`false`), nil
	case strings.HasPrefix(goType, "[]"):
		return json.RawMessage(`[]`), nil
	}
	return json.RawMessage(`null`), nil
}

// bundle returns the spec with the problem files merged in and every
// x-problems list turned into error responses. The lists stay in the
// bundle: the writer checks an answered problem against its operation's.
func (b *bundler) bundle() ([]byte, error) {
	components := ensure(b.root, "components")
	schemas := ensure(components, "schemas")
	responses := ensure(components, "responses")

	for _, s := range b.schemas {
		if get(schemas, s.name) != nil {
			return nil, fmt.Errorf("%s: schema %s is also declared by the spec", s.file, s.name)
		}
		set(schemas, s.name, s.node)
	}
	for _, p := range b.problems {
		name := p.Name + problemSuffix
		if get(schemas, name) != nil || get(responses, name) != nil {
			return nil, fmt.Errorf("%s: %s collides with the spec's own %s", p.file, p.Name, name)
		}
		set(schemas, name, p.schema())
		set(responses, name, mapping(
			"description", p.Title+": "+oneLine(p.Description),
			"content", mapping("application/problem+json", mapping(
				"schema", ref("schemas", name),
			)),
		))
	}

	err := b.operationResponses()
	if err != nil {
		return nil, err
	}

	b.doc.HeadComment = strings.TrimSpace(header + "\n\n" + b.doc.HeadComment)
	var out bytes.Buffer
	enc := yaml.NewEncoder(&out)
	enc.SetIndent(2)
	err = enc.Encode(b.doc)
	if err != nil {
		return nil, err
	}
	return out.Bytes(), enc.Close()
}

// schema expands p into its full problem schema: the base Problem with
// p's status and title fixed and p's members added. The consts keep their
// plain Go types: oapi-codegen would name an enum constant after the
// title's value, which can collide with the spec's own types, and Go
// builds problems through the constructors anyway.
func (p *problem) schema() *yaml.Node {
	props := mapping(
		"type", mapping(
			"type", "string",
			"format", "uri",
			"pattern", "/problems/"+p.Slug+"$",
		),
		"status", mapping("type", "integer", "const", p.Status, "x-go-type", "int"),
		"title", mapping("type", "string", "const", p.Title, "x-go-type", "string"),
	)
	required := make([]string, 0, 3+len(p.Members))
	required = append(required, "type", "status", "title")
	for _, m := range p.Members {
		set(props, m.Name, m.schema)
		required = append(required, m.Name)
	}
	ext := mapping("type", "object", "required", required, "properties", props)
	return mapping(
		"description", p.Description,
		"x-problem", p.xProblem,
		"allOf", node([]*yaml.Node{ref("schemas", "Problem"), ext}),
	)
}

func (b *bundler) operationResponses() error {
	bySlug := map[string]*problem{}
	for _, p := range b.problems {
		bySlug[p.Slug] = p
	}
	paths := get(b.root, "paths")
	if paths == nil {
		return nil
	}
	for i := 0; i < len(paths.Content); i += 2 {
		path, item := paths.Content[i].Value, paths.Content[i+1]
		for _, method := range methods {
			op := get(item, method)
			if op == nil {
				continue
			}
			list := get(op, "x-problems")
			if list == nil {
				continue
			}
			where := strings.ToUpper(method) + " " + path
			var slugs []string
			err := list.Decode(&slugs)
			if err != nil {
				return fmt.Errorf("%s: x-problems: %w", where, err)
			}
			byStatus := map[int][]*problem{}
			for _, slug := range slugs {
				p, ok := bySlug[slug]
				if !ok {
					return fmt.Errorf("%s: x-problems names undeclared problem %s", where, slug)
				}
				if slices.Contains(byStatus[p.Status], p) {
					return fmt.Errorf("%s: x-problems names %s twice", where, slug)
				}
				byStatus[p.Status] = append(byStatus[p.Status], p)
			}
			responses := ensure(op, "responses")
			statuses := make([]int, 0, len(byStatus))
			for s := range byStatus {
				statuses = append(statuses, s)
			}
			slices.Sort(statuses)
			for _, status := range statuses {
				code := strconv.Itoa(status)
				if get(responses, code) != nil {
					return fmt.Errorf("%s: %s is declared both in responses and by x-problems", where, code)
				}
				set(responses, code, response(byStatus[status]))
			}
		}
	}
	return nil
}

// response is one status's error response: the problem's own, or a oneOf
// when several problems share the status.
func response(ps []*problem) *yaml.Node {
	if len(ps) == 1 {
		return ref("responses", ps[0].Name+problemSuffix)
	}
	titles := make([]string, len(ps))
	refs := make([]*yaml.Node, len(ps))
	for i, p := range ps {
		titles[i] = p.Title
		refs[i] = ref("schemas", p.Name+problemSuffix)
	}
	return mapping(
		"description", strings.Join(titles, ", or "),
		"content", mapping("application/problem+json", mapping(
			"schema", mapping("oneOf", node(refs)),
		)),
	)
}

// ── yaml.Node helpers ──────────────────────────────────────────────────

func get(m *yaml.Node, key string) *yaml.Node {
	if m == nil || m.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			return m.Content[i+1]
		}
	}
	return nil
}

func set(m *yaml.Node, key string, v *yaml.Node) {
	for i := 0; i < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			m.Content[i+1] = v
			return
		}
	}
	m.Content = append(m.Content, node(key), v)
}

// ensure returns m's mapping under key, adding an empty one if missing.
func ensure(m *yaml.Node, key string) *yaml.Node {
	if v := get(m, key); v != nil {
		return v
	}
	v := &yaml.Node{Kind: yaml.MappingNode}
	set(m, key, v)
	return v
}

// mapping builds a mapping from alternating keys and values; a value is a
// *yaml.Node or anything node encodes.
func mapping(kv ...any) *yaml.Node {
	m := &yaml.Node{Kind: yaml.MappingNode}
	for i := 0; i+1 < len(kv); i += 2 {
		set(m, kv[i].(string), node(kv[i+1])) //nolint:forcetypeassert // keys are literals
	}
	return m
}

func ref(kind, name string) *yaml.Node {
	return mapping("$ref", "#/components/"+kind+"/"+name)
}

func node(v any) *yaml.Node {
	if n, ok := v.(*yaml.Node); ok {
		return n
	}
	var n yaml.Node
	err := n.Encode(v)
	if err != nil {
		panic(err) // only literals and slices of them reach here
	}
	return &n
}
