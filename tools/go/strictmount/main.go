// Command strictmount writes the strict server's glue into a Backend:
//
//   - mount.gen.go in the generated openapi package: the one Mount function
//     that serves the strict server through the harness's strict stack
//     (httpserver.StrictStack). The option structs and the strict function
//     types it fills are generated per package, so the glue cannot live in
//     lib/httpserver; generating it keeps one copy of it in the repo.
//   - server.gen.go in internal/app: the server type that embeds the
//     Handlers of every feature folder that declares one, so adding a
//     feature doesn't mean editing a list.
//
// It runs after oapi-codegen, from the Backend's directory:
// go run tools/strictmount internal/openapi/mount.gen.go internal/app/server.gen.go
package main

import (
	"fmt"
	"os"
)

const source = `// Code generated by tools/strictmount. DO NOT EDIT.

package openapi

import (
	"net/http"

	"lib/httpserver"

	"github.com/go-chi/chi/v5"
)

// Mount serves the strict server on r through the harness: validation,
// spec-derived auth dispatch, tracing and the unified error mapping,
// checked against each operation's x-problems. mws run before the strict
// server decodes the request (a webhook's raw-body capture).
func Mount(r chi.Router, s StrictServerInterface, chains map[string][]func(http.Handler) http.Handler, mws ...MiddlewareFunc) {
	harness := httpserver.StrictStack(chains)
	stack := make([]StrictMiddlewareFunc, 0, len(harness))
	for _, mw := range harness {
		stack = append(stack, func(f StrictHandlerFunc, operationID string) StrictHandlerFunc {
			return StrictHandlerFunc(mw(httpserver.StrictHandlerFunc(f), operationID))
		})
	}
	strict := NewStrictHandlerWithOptions(s, stack, StrictHTTPServerOptions{
		RequestErrorHandlerFunc:  httpserver.WriteBodyError,
		ResponseErrorHandlerFunc: httpserver.WriteError,
	})
	HandlerWithOptions(strict, ChiServerOptions{
		BaseRouter:       r,
		Middlewares:      append([]MiddlewareFunc{httpserver.OperationSlot}, mws...),
		ErrorHandlerFunc: httpserver.WriteParamError,
	})
}
`

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: strictmount <mount output> <server output>")
		os.Exit(2)
	}
	err := os.WriteFile(os.Args[1], []byte(source), 0o600) //nolint:gosec // codegen step run by just gen and the Dockerfiles; the path is the build's own, not untrusted input
	if err == nil {
		err = writeServer(os.Args[2])
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "strictmount:", err)
		os.Exit(1)
	}
}
