package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// feature is one folder under internal/features that declares a Handlers
// type: the strict server embeds it.
type feature struct {
	path  string // import path
	pkg   string // package name
	field string // embedded field and alias name, e.g. apiKeysHandlers
}

// findFeatures lists the features under dir (internal/features) that
// declare `type Handlers`, sorted by folder, with import paths under module.
func findFeatures(module, dir string) ([]feature, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []feature
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		pkg, ok, err := handlersPackage(filepath.Join(dir, e.Name()))
		if err != nil {
			return nil, err
		}
		if !ok {
			continue
		}
		out = append(out, feature{
			path:  module + "/internal/features/" + e.Name(),
			pkg:   pkg,
			field: camel(e.Name()) + "Handlers",
		})
	}
	return out, nil
}

// handlersPackage reports the package name of the folder's non-test files
// and whether one of them declares a Handlers type.
func handlersPackage(dir string) (string, bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", false, err
	}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return "", false, err
		}
		if declaresType(f, "Handlers") {
			return f.Name.Name, true, nil
		}
	}
	return "", false, nil
}

func declaresType(f *ast.File, name string) bool {
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			if ts, ok := s.(*ast.TypeSpec); ok && ts.Name.Name == name {
				return true
			}
		}
	}
	return false
}

// camel turns a folder name into lowerCamelCase: api_keys → apiKeys.
func camel(s string) string {
	parts := strings.Split(s, "_")
	for i := 1; i < len(parts); i++ {
		if parts[i] != "" {
			parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
		}
	}
	return strings.Join(parts, "")
}

// serverSource is the Backend's server.gen.go: the server type that
// implements the strict interface by embedding every feature's Handlers.
func serverSource(module string, features []feature) ([]byte, error) {
	if len(features) == 0 {
		return nil, errors.New("no feature declares a Handlers type")
	}
	var b bytes.Buffer
	b.WriteString(`// Code generated by tools/strictmount. DO NOT EDIT.

package app

import (
`)
	imports := make([]string, 0, len(features)+1)
	for _, f := range features {
		line := fmt.Sprintf("\t%q\n", f.path)
		if f.pkg != filepath.Base(f.path) {
			line = fmt.Sprintf("\t%s %q\n", f.pkg, f.path)
		}
		imports = append(imports, line)
	}
	imports = append(imports, fmt.Sprintf("\t%q\n", module+"/internal/openapi"))
	slices.Sort(imports)
	b.WriteString(strings.Join(imports, ""))
	b.WriteString(`)

// server implements openapi.StrictServerInterface by embedding the Handlers
// of every feature that has one: method promotion satisfies the generated
// interface with no delegation glue, and raw routes (a websocket, a stream)
// are promoted the same way. The aliases only give each embedded field its
// own name; embedding two *X.Handlers directly would collide on "Handlers".
type (
`)
	for _, f := range features {
		fmt.Fprintf(&b, "\t%s = %s.Handlers\n", f.field, f.pkg)
	}
	b.WriteString(")\n\ntype server struct {\n")
	for _, f := range features {
		fmt.Fprintf(&b, "\t*%s\n", f.field)
	}
	b.WriteString("}\n\nvar _ openapi.StrictServerInterface = (*server)(nil)\n")
	return format.Source(b.Bytes())
}

// writeServer generates out from the Backend in the current directory.
func writeServer(out string) error {
	mod, err := os.ReadFile("go.mod")
	if err != nil {
		return err
	}
	module, ok := modulePath(mod)
	if !ok {
		return errors.New("go.mod has no module line")
	}
	features, err := findFeatures(module, filepath.Join("internal", "features"))
	if err != nil {
		return err
	}
	src, err := serverSource(module, features)
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o600) //nolint:gosec // codegen step; the path is the build's own
}

// modulePath reads the module line of a go.mod.
func modulePath(mod []byte) (string, bool) {
	for line := range strings.Lines(string(mod)) {
		rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module ")
		if ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), true
		}
	}
	return "", false
}
